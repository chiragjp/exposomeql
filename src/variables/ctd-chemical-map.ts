/** Lookup by MeSH ID → chemical mapping. Note: multiple chemicals may share a MeSH ID (metabolites → parent). */
export const CTD_BY_MESH: Map<string, CTDChemicalMapping[]> = new Map();

/** Lookup by NHANES variable code → chemical mapping */
export const CTD_BY_NHANES: Map<string, CTDChemicalMapping> = new Map();

/** Lookup by HHEAR analyte code → chemical mapping */
export const CTD_BY_HHEAR: Map<string, CTDChemicalMapping> = new Map();

/** Lookup by CAS registry number → chemical mapping */
export const CTD_BY_CAS: Map<string, CTDChemicalMapping> = new Map();

/** Lookup by category → chemical mappings */
export const CTD_BY_CATEGORY: Map<string, CTDChemicalMapping[]> = new Map();

// Initialize all indexes
for (const chem of CTD_CHEMICAL_MAP) {
  // MeSH index (one-to-many: multiple chemicals can share a MeSH ID)
  if (!CTD_BY_MESH.has(chem.mesh_id)) {
    CTD_BY_MESH.set(chem.mesh_id, []);
  }
  CTD_BY_MESH.get(chem.mesh_id)!.push(chem);

  // CAS index
  if (chem.cas) {
    CTD_BY_CAS.set(chem.cas, chem);
  }

  // HHEAR index
  if (chem.hhear_code) {
    CTD_BY_HHEAR.set(chem.hhear_code, chem);
  }

  // NHANES index
  for (const v of chem.nhanes_vars) {
    CTD_BY_NHANES.set(v, chem);
  }

  // Category index
  if (!CTD_BY_CATEGORY.has(chem.category)) {
    CTD_BY_CATEGORY.set(chem.category, []);
  }
  CTD_BY_CATEGORY.get(chem.category)!.push(chem);
}

/**
 * Resolve a chemical by any identifier (NHANES var, HHEAR code, CAS, MeSH ID, or name substring).
 * Returns matching CTDChemicalMapping entries.
 */
export function resolveChemicalForCTD(query: string): CTDChemicalMapping[] {
  const q = query.trim().toUpperCase();

  // Try NHANES var
  const byNhanes = CTD_BY_NHANES.get(q);
  if (byNhanes) return [byNhanes];

  // Try HHEAR code
  const byHhear = CTD_BY_HHEAR.get(q);
  if (byHhear) return [byHhear];

  // Try CAS (case-insensitive not needed, but normalize)
  const byCas = CTD_BY_CAS.get(query.trim());
  if (byCas) return [byCas];

  // Try MeSH ID
  const byMesh = CTD_BY_MESH.get(q) || CTD_BY_MESH.get(query.trim());
  if (byMesh) return byMesh;

  // Fallback: name substring search
  const lq = query.trim().toLowerCase();
  return CTD_CHEMICAL_MAP.filter(
    (c) =>
      c.chemical_name.toLowerCase().includes(lq) ||
      (c.parent_compound && c.parent_compound.toLowerCase().includes(lq))
  );
}
