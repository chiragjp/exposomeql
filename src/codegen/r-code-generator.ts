/**
 * Large-scale ExWAS — every available exposure against one outcome.
 * Mirrors nhanes_exwas.R, but emits the wrapper from the nhanespewas package
 * (the on-server version pre-computes; locally you'd loop or use the helper).
 */
export function generateExwasCode(
  outcome: VariableEntry,
  params: { cycles?: string[]; covariates?: string[] | null; fdr?: number },
): string {
  const cov = params.covariates ?? ["RIDAGEYR", "RIAGENDR", "INDFMPIR"];
  const fdr = params.fdr ?? 0.05;
  return `${rHeader("nhanes_exwas", `ExWAS: every NHANES exposure vs. ${outcome.variableName}`)}
${seriesDecl(params.cycles)}

# Get the catalog of exposure variables on the server
exposure_list <- list_nhanes_exposures(con)$variableName

# Per-exposure survey-weighted regression. Pre-computed catalogs (the EP-WAS
# tools) are much faster on-server; this loop is for local re-execution.
results <- lapply(exposure_list, function(exp_var) {
  tryCatch({
    pooled_x <- NULL
    for (s in series) {
      tab <- tryCatch(get_tables(exp_var, "${outcome.variableName}", s, con), error = function(e) NULL)
      if (is.null(tab) || nrow(tab$merged_tab) == 0) return(NULL)
      tab <- figure_out_weight(tab)
      d <- tab$merged_tab; d$series <- s
      if (is.null(pooled_x)) pooled_x <- d
      else { cc <- intersect(names(pooled_x), names(d)); pooled_x <- rbind(pooled_x[, cc], d[, cc]) }
    }
    if (is.null(pooled_x) || nrow(pooled_x) < 50) return(NULL)
    n_cycles <- length(unique(pooled_x$series))
    if (n_cycles > 1) {
      if (n_cycles == 2 && all(c("A", "B") %in% unique(pooled_x$series))
          && "WTMEC4YR" %in% names(pooled_x)) {
        pooled_x$wt <- pooled_x$WTMEC4YR
      } else {
        pooled_x$wt <- pooled_x$wt / n_cycles
      }
    }
    pooled_x <- pooled_x[complete.cases(pooled_x[, intersect(c(exp_var, "${outcome.variableName}", ${cov.map((c) => `"${c}"`).join(", ")}, "wt"), names(pooled_x))]), ]
    pooled_x <- pooled_x[pooled_x$wt > 0, ]
    dsn_x <- svydesign(ids = ~SDMVPSU, strata = ~SDMVSTRA, weights = ~wt, nest = TRUE, data = pooled_x)
    options(survey.lonely.psu = "adjust")
    fml <- as.formula(paste0("\`${outcome.variableName}\` ~ \`", exp_var, "\` + ", paste(c(${cov.map((c) => `"${c}"`).join(", ")}), collapse = " + ")))
    fit <- svyglm(fml, design = dsn_x)
    co <- summary(fit)$coefficients[2, ]
    data.frame(exposure = exp_var, estimate = co[1], se = co[2], p_value = co[4], n = nrow(pooled_x))
  }, error = function(e) NULL)
})
out <- do.call(rbind, results)
out$q_value <- p.adjust(out$p_value, method = "BH")
out <- out[order(out$p_value), ]
significant <- out[out$q_value < ${fdr}, ]
print(significant)

${R_FOOTER}
`;
}

