export function generateMortalitySearchCode(params: {
  exposure?: string; cause?: string; top_n?: number;
}): string {
  const cause = params.cause ?? "all";
  return `# Mortality ExWAS — reproduce ${params.exposure ? `the row for ${params.exposure}` : `the screen`} from
# scratch using the underlying NHANES × NDI Cox PH that mortality_search summarizes.
# Generated by ExposomeQL (mortality_search) on ${new Date().toISOString()}
#
# The on-server tool reads a pre-computed catalog (mortality_exwas table).
# This script recomputes it from first principles using nhanespewas. To get
# the same numbers as the catalog, loop over the full exposure list; for a
# spot-check on a single exposure, set exposure_list to one variable.

library(survey); library(survival); library(nhanespewas); library(dplyr)

con <- connect_pewas_data("path/to/nhanes_031725.sqlite")

exposure_list <- ${params.exposure ? `c("${params.exposure}")` : "list_nhanes_exposures(con)$variableName"}
cause <- "${cause}"   # "all", "heart", "cancer", "diabetes_ucod", "cerebrovascular", "kidney"
covariates <- c("RIDAGEYR", "RIAGENDR", "RIDRETH1", "INDFMPIR", "DMDEDUC2")

yr2s <- c("1999"="A","2001"="B","2003"="C","2005"="D","2007"="E","2009"="F","2011"="G","2013"="H","2015"="I","2017"="J")

results <- lapply(exposure_list, function(exp_var) {
  tryCatch({
    cycles <- get_table_names_for_varname(con, exp_var)$Begin.Year |>
      as.character() |> (\\(y) yr2s[y])() |> unique() |> sort()
    pooled <- NULL
    for (s in cycles) {
      tab <- get_tables(exp_var, exp_var, s, con)
      tab <- figure_out_weight(tab)
      d <- tab$merged_tab; d$series <- s
      if (is.null(pooled)) pooled <- d
      else { cc <- intersect(names(pooled), names(d)); pooled <- rbind(pooled[, cc], d[, cc]) }
    }
    n_cycles <- length(unique(pooled$series))
    if (n_cycles > 1) {
  if (n_cycles == 2 && all(c("A", "B") %in% unique(pooled$series))
      && "WTMEC4YR" %in% names(pooled)) {
    pooled$wt <- pooled$WTMEC4YR
  } else {
    pooled$wt <- pooled$wt / n_cycles
  }
}
    # Mortality columns from the linked-mortality merge: permth_int (months
    # from interview to death/censor), mortality_status (1=died, 0=censor).
    if (cause != "all") {
      pooled$mortality_status <- ifelse(pooled$cause_recode == cause, pooled$mortality_status, 0)
    }
    required <- c(exp_var, "permth_int", "mortality_status", covariates, "wt")
    pooled <- pooled[complete.cases(pooled[, intersect(required, names(pooled))]), ]
    pooled <- pooled[pooled[[exp_var]] > 0, ]
    pooled$exposure_z <- as.numeric(scale(log10(pooled[[exp_var]])))
    fml <- as.formula(paste0("Surv(permth_int, mortality_status) ~ exposure_z + ", paste(covariates, collapse = " + ")))
    fit <- coxph(fml, data = pooled, weights = wt)
    s <- summary(fit)$coefficients
    data.frame(
      exposure  = exp_var,
      log_hr    = s[1, 1],
      hr        = exp(s[1, 1]),
      hr_lower  = exp(s[1, 1] - 1.96 * s[1, 3]),
      hr_upper  = exp(s[1, 1] + 1.96 * s[1, 3]),
      p_value   = s[1, 5],
      n         = nrow(pooled),
      n_events  = sum(pooled$mortality_status)
    )
  }, error = function(e) NULL)
})
out <- do.call(rbind, results)
out$bonferroni_threshold <- 0.05 / nrow(out)
out <- out[order(out$p_value), ]
${params.top_n ? `print(head(out, ${params.top_n}))` : "print(out)"}

${R_FOOTER}
`;
}

