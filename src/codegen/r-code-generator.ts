export function generateConditionalCode(
  outcome: VariableEntry,
  given: VariableEntry,
  params: { bins?: number; subgroup?: string }
): string {
  const nBins = params.bins ?? 10;
  return `# Survey-weighted conditional mean: ${outcome.variableName} by ${given.variableName}
# Generated by ExposomeQL on ${new Date().toISOString()}

library(survey)
library(nhanespewas)
library(dplyr)

con <- connect_pewas_data("path/to/nhanes_031725.sqlite")

# Get merged data with both variables
# ... (use get_tables for both variables)

dsn <- svydesign(
  ids = ~SDMVPSU, strata = ~SDMVSTRA,
  weights = ~wt, nest = TRUE, data = dat
)
options(survey.lonely.psu = "adjust")

# Create ${nBins} bins of the conditioning variable
breaks <- svyquantile(~${given.variableName}, dsn, quantiles = seq(0, 1, length = ${nBins + 1}), na.rm = TRUE)
dat$bin <- cut(dat$${given.variableName}, breaks = breaks[[1]], include.lowest = TRUE)

# Compute conditional means
result <- svyby(~${outcome.variableName}, ~bin, dsn, svymean, na.rm = TRUE)
print(result)

disconnect_pewas_data(con)
`;
}
