/** Series letter declaration: `series <- c("I", "J")` or a comment. */
function seriesDecl(cycles?: string[]): string {
  const series = cycles?.map((c) => CYCLE_TO_SERIES[c] ?? c) ?? [];
  return series.length > 0
    ? `series <- c(${series.map((s) => `"${s}"`).join(", ")})`
    : "# Use whichever cycles your local DB has for these vars\nseries <- get_table_names_for_varname(con, \"VAR\")$series  # adjust";
}

/** Standard top: comment header + library imports + connection. */
function rHeader(toolName: string, summary: string): string {
  return `# ${summary}
# Generated by ExposomeQL (${toolName}) on ${new Date().toISOString()}

library(survey)
library(nhanespewas)
library(dplyr)

con <- connect_pewas_data("path/to/nhanes_031725.sqlite")`;
}

/** Standard footer: disconnect. */
const R_FOOTER = `disconnect_pewas_data(con)`;

/** Render an R c(...) literal from an array of strings. */
function rChar(arr?: string[] | null): string {
  if (!arr || arr.length === 0) return "NULL";
  return `c(${arr.map((s) => `"${s.replace(/"/g, '\\"')}"`).join(", ")})`;
}

/** Render an R c(...) literal from an array of numbers. */
function rNum(arr?: number[] | null): string {
  if (!arr || arr.length === 0) return "NULL";
  return `c(${arr.join(", ")})`;
}

/** Standard "pool across cycles" block: pulls the named vars from each
 *  series letter, attaches survey weights, and concatenates into a single
 *  `pooled` data frame. Re-used by most NHANES tool generators.
 *
 *  Multi-cycle weighting matches the runtime: when exactly cycles A + B
 *  are pooled NCHS publishes a 4-year weight (`WTMEC4YR`) and the runtime
 *  uses it directly; otherwise we divide the per-cycle weight by the
 *  number of cycles. The `P_*` (pre-pandemic pooled) tables use a
 *  different weight scheme (`WTMECPRP`) and must NOT be pooled with the
 *  A–J cycles — extra-covariate joins should filter them out:
 *    `tinfo <- tinfo[!grepl("^P_", tinfo$Data.File.Name), ]` */
function poolBlock(primary: string, secondary: string = primary): string {
  return `pooled <- NULL
for (s in series) {
  tab <- tryCatch(get_tables("${primary}", "${secondary}", s, con), error = function(e) NULL)
  if (is.null(tab) || nrow(tab$merged_tab) == 0) next
  tab <- figure_out_weight(tab)
  d <- tab$merged_tab
  d$series <- s
  if (is.null(pooled)) pooled <- d
  else { cc <- intersect(names(pooled), names(d)); pooled <- rbind(pooled[, cc], d[, cc]) }
}
n_cycles <- length(unique(pooled$series))
if (n_cycles > 1) {
  if (n_cycles == 2 && all(c("A", "B") %in% unique(pooled$series))
      && "WTMEC4YR" %in% names(pooled)) {
    pooled$wt <- pooled$WTMEC4YR
  } else {
    pooled$wt <- pooled$wt / n_cycles
  }
}`;
}

/** Standard svydesign + lonely-PSU adjust. */
const SVY_DESIGN = `dsn <- svydesign(ids = ~SDMVPSU, strata = ~SDMVSTRA, weights = ~wt, nest = TRUE, data = pooled)
options(survey.lonely.psu = "adjust")`;

/** Standard "drop incomplete + zero-weight rows" boilerplate, given a list
 *  of required column names. */
function completeRows(required: string[]): string {
  return `required <- c(${required.map((r) => `"${r}"`).join(", ")}, "wt")
pooled <- pooled[complete.cases(pooled[, intersect(required, names(pooled))]), ]
pooled <- pooled[pooled$wt > 0, ]`;
}

/**
 * Generate reproducible R code for survey-weighted mean computation.
 *
 * Loops `get_tables` per cycle so the multi-cycle weight ladder
 * (`WTMEC4YR` for A+B, `wt / n_cycles` otherwise) matches the runtime
 * `nhanes_mean.R` exactly. Earlier versions called `get_tables` once
 * with the cycle vector and skipped weight pooling — this divergence
 * produced subtly different numbers for any 2+ cycle pool.
 */
export function generateMeanCode(
  variable: VariableEntry,
  params: { subgroup?: string; cycles?: string[] }
): string {
  return `# Survey-weighted mean of ${variable.description} (${variable.variableName})
# Generated by ExposomeQL (nhanes_mean) on ${new Date().toISOString()}

library(survey)
library(nhanespewas)
library(dplyr)

con <- connect_pewas_data("path/to/nhanes_031725.sqlite")
${seriesDecl(params.cycles)}

${poolBlock(variable.variableName)}
${completeRows([variable.variableName])}
${params.subgroup ? `pooled <- pooled |> filter(${params.subgroup})\n` : ""}
${SVY_DESIGN}

result <- svymean(~\`${variable.variableName}\`, design = dsn, na.rm = TRUE)
ci <- confint(result)
cat(sprintf("Mean: %.4f (95%% CI: %.4f - %.4f)\\n", coef(result), ci[1], ci[2]))
cat(sprintf("SE: %.4f\\n", SE(result)))
cat(sprintf("N (unweighted): %d\\n", nrow(pooled)))

${R_FOOTER}
`;
}

/**
 * Generate reproducible R code for prevalence computation.
 *
 * Same per-cycle loop + WTMEC4YR ladder as generateMeanCode so multi-cycle
 * pools match the runtime numerically.
 */
export function generatePrevalenceCode(
  variable: VariableEntry,
  params: { condition: string; subgroup?: string; cycles?: string[] }
): string {
  return `# Survey-weighted prevalence: ${params.condition}
# Generated by ExposomeQL on ${new Date().toISOString()}

library(survey)
library(nhanespewas)
library(dplyr)

con <- connect_pewas_data("path/to/nhanes_031725.sqlite")
${seriesDecl(params.cycles)}

${poolBlock(variable.variableName)}
pooled <- pooled |> filter(!is.na(\`${variable.variableName}\`)) |>
  mutate(condition = as.numeric(${params.condition}))
${params.subgroup ? `pooled <- pooled |> filter(${params.subgroup})\n` : ""}
${completeRows([variable.variableName])}
${SVY_DESIGN}

# Compute prevalence
result <- svymean(~condition, design = dsn, na.rm = TRUE)
ci <- confint(result)

cat(sprintf("Prevalence: %.1f%% (95%% CI: %.1f%% - %.1f%%)\\n",
  coef(result) * 100, ci[1] * 100, ci[2] * 100))

disconnect_pewas_data(con)
`;
}

/**
 * Generate reproducible R code for conditional reference intervals via
 * quantile regression. Mirrors nhanes_reference_interval.R: fits the
 * biomarker as biomarker ~ age + age² + sex at multiple τ, then predicts
 * at user-specified ages. Produces "what's normal for someone like me?"
 * intervals from NHANES.
 */
export function generateReferenceIntervalCode(
  biomarker: VariableEntry,
  params: {
    cycles?: string[];
    taus?: number[];
    predict_age?: number[];
    predict_sex?: string;
    age_spline?: boolean;
  },
): string {
  const taus = params.taus ?? [0.025, 0.05, 0.25, 0.5, 0.75, 0.95, 0.975];
  const ages = params.predict_age ?? [20, 30, 40, 50, 60, 70];
  const ageSpline = params.age_spline !== false;
  const fml = ageSpline ? "y ~ age + I(age^2) + sex" : "y ~ age + sex";

  return `${rHeader("nhanes_reference_interval", `Conditional reference intervals for ${biomarker.description} (${biomarker.variableName})`)}
library(quantreg)

${seriesDecl(params.cycles)}
taus <- ${rNum(taus)}

# Pool ${biomarker.variableName} + DEMO across cycles
pooled <- NULL
for (s in series) {
  tab <- tryCatch(get_tables("${biomarker.variableName}", "${biomarker.variableName}", s, con), error = function(e) NULL)
  if (is.null(tab) || nrow(tab$merged_tab) == 0) next
  tab <- figure_out_weight(tab)
  d <- tab$merged_tab
  d$series <- s
  if (is.null(pooled)) pooled <- d
  else { cc <- intersect(names(pooled), names(d)); pooled <- rbind(pooled[, cc], d[, cc]) }
}
n_cycles <- length(unique(pooled$series))
if (n_cycles > 1) {
  if (n_cycles == 2 && all(c("A", "B") %in% unique(pooled$series))
      && "WTMEC4YR" %in% names(pooled)) {
    pooled$wt <- pooled$WTMEC4YR
  } else {
    pooled$wt <- pooled$wt / n_cycles
  }
}

# Require complete age + sex + biomarker
required <- c("${biomarker.variableName}", "RIDAGEYR", "RIAGENDR", "wt")
pooled <- pooled[complete.cases(pooled[, intersect(required, names(pooled))]), ]
pooled <- pooled[pooled$wt > 0, ]

pooled$sex <- as.factor(pooled$RIAGENDR)
pooled$age <- pooled$RIDAGEYR
pooled$y   <- pooled$\`${biomarker.variableName}\`

# Quantile regression at each τ — returns the conditional percentile
# function as a function of age + sex.
fits <- lapply(taus, function(tau) rq(${fml}, data = pooled, tau = tau, weights = pooled$wt))

# Predict at the requested ages × sex levels
ages <- ${rNum(ages)}
sex_vals <- ${params.predict_sex === "both" || !params.predict_sex
  ? "levels(pooled$sex)"
  : `as.character("${params.predict_sex}")`}

grid <- expand.grid(age = ages, sex = sex_vals)
preds <- sapply(fits, function(f) predict(f, newdata = grid))
colnames(preds) <- paste0("p", round(taus * 100, 1))
out <- cbind(grid, round(preds, 4))
print(out)

${R_FOOTER}
`;
}

/**
 * Generate reproducible R code for survey-weighted multi-τ quantile
 * regression. Mirrors nhanes_quantile_regression.R: outcome ~ exposure +
 * covariates fit at each τ, optionally with log10(exposure).
 */
export function generateQuantileRegressionCode(
  exposure: VariableEntry,
  outcome: VariableEntry,
  params: {
    cycles?: string[];
    covariates?: string[] | null;
    taus?: number[];
    log_exposure?: boolean;
  },
): string {
  const taus = params.taus ?? [0.05, 0.1, 0.25, 0.5, 0.75, 0.9, 0.95];
  const log = params.log_exposure !== false;
  const cov = params.covariates ?? [];
  const xform = log ? `log10(\`${exposure.variableName}\`)` : `\`${exposure.variableName}\``;
  const covPart = cov.length > 0 ? ` + ${cov.map((c) => `\`${c}\``).join(" + ")}` : "";

  return `${rHeader("nhanes_quantile_regression", `Quantile regression: ${outcome.variableName} ~ ${exposure.variableName}${cov.length ? " + covariates" : ""}`)}
library(quantreg)

${seriesDecl(params.cycles)}
taus <- ${rNum(taus)}
covariates <- ${rChar(cov)}

# Pool exposure + outcome (+ covariates) across cycles
pooled <- NULL
for (s in series) {
  tab <- tryCatch(get_tables("${exposure.variableName}", "${outcome.variableName}", s, con), error = function(e) NULL)
  if (is.null(tab) || nrow(tab$merged_tab) == 0) next
  tab <- figure_out_weight(tab)
  d <- tab$merged_tab
  d$series <- s
  if (is.null(pooled)) pooled <- d
  else { cc <- intersect(names(pooled), names(d)); pooled <- rbind(pooled[, cc], d[, cc]) }
}
n_cycles <- length(unique(pooled$series))
if (n_cycles > 1) {
  if (n_cycles == 2 && all(c("A", "B") %in% unique(pooled$series))
      && "WTMEC4YR" %in% names(pooled)) {
    pooled$wt <- pooled$WTMEC4YR
  } else {
    pooled$wt <- pooled$wt / n_cycles
  }
}

required <- c("${exposure.variableName}", "${outcome.variableName}", covariates, "wt")
pooled <- pooled[complete.cases(pooled[, intersect(required, names(pooled))]), ]
pooled <- pooled[pooled$wt > 0, ]
${log ? `pooled <- pooled[pooled$\`${exposure.variableName}\` > 0, ]  # log10 needs positive values\n` : ""}
# τ-by-τ fit: estimate of the exposure coefficient at each conditional quantile
fml <- as.formula(paste0("\`${outcome.variableName}\` ~ ${log ? "I(log10(`" + exposure.variableName + "`))" : "`" + exposure.variableName + "`"}", if (length(covariates) > 0) paste0(" + ", paste(covariates, collapse = " + ")) else ""))
fits <- lapply(taus, function(tau) rq(fml, data = pooled, tau = tau, weights = pooled$wt))

# Extract exposure coefficient (row 2) at each τ
exposure_term <- ${log ? `paste0("I(log10(\`${exposure.variableName}\`))")` : `"\`${exposure.variableName}\`"`}
result <- do.call(rbind, lapply(seq_along(taus), function(i) {
  s <- summary(fits[[i]], se = "nid")
  co <- coef(s)
  data.frame(
    tau = taus[i],
    estimate = co[2, 1],
    std_error = co[2, 2],
    p_value   = co[2, 4]
  )
}))
print(result)

${R_FOOTER}
`;
}

/**
 * Generate reproducible R code for survey-weighted regression.
 * Covers nhanes_model and nhanes_dose_response (both fit a single model;
 * dose-response just adds spline terms on the exposure).
 */
export function generateModelCode(
  outcome: VariableEntry,
  predictors: VariableEntry[],
  params: { cycles?: string[]; family?: string; doseResponse?: boolean; subgroup?: string },
): string {
  const fam = params.family ?? "gaussian";
  const isLogit = fam === "binomial";
  const dr = !!params.doseResponse;
  const exposure = predictors[0]?.variableName ?? "";
  const cov = predictors.slice(1).map((p) => `\`${p.variableName}\``);

  const rhs = dr
    ? `splines::ns(\`${exposure}\`, df = 4)${cov.length ? " + " + cov.join(" + ") : ""}`
    : `${predictors.map((p) => `\`${p.variableName}\``).join(" + ")}`;

  const fitCall = isLogit
    ? `svyglm(\`${outcome.variableName}\` ~ ${rhs}, design = dsn, family = quasibinomial())`
    : `svyglm(\`${outcome.variableName}\` ~ ${rhs}, design = dsn)`;

  return `${rHeader(dr ? "nhanes_dose_response" : "nhanes_model", `Survey-weighted ${dr ? "dose-response model" : "regression"}: ${outcome.variableName} ~ ${exposure}${cov.length ? " + covariates" : ""}`)}
${dr ? "library(splines)" : ""}

${seriesDecl(params.cycles)}

# Pool outcome + predictors across cycles
pooled <- NULL
for (s in series) {
  tab <- tryCatch(get_tables("${exposure}", "${outcome.variableName}", s, con), error = function(e) NULL)
  if (is.null(tab) || nrow(tab$merged_tab) == 0) next
  tab <- figure_out_weight(tab)
  d <- tab$merged_tab
  d$series <- s
  if (is.null(pooled)) pooled <- d
  else { cc <- intersect(names(pooled), names(d)); pooled <- rbind(pooled[, cc], d[, cc]) }
}
n_cycles <- length(unique(pooled$series))
if (n_cycles > 1) {
  if (n_cycles == 2 && all(c("A", "B") %in% unique(pooled$series))
      && "WTMEC4YR" %in% names(pooled)) {
    pooled$wt <- pooled$WTMEC4YR
  } else {
    pooled$wt <- pooled$wt / n_cycles
  }
}

required <- c("${outcome.variableName}", "${exposure}", ${rChar(predictors.slice(1).map((p) => p.variableName))}, "wt")
pooled <- pooled[complete.cases(pooled[, intersect(required, names(pooled))]), ]
pooled <- pooled[pooled$wt > 0, ]
${params.subgroup ? `pooled <- pooled |> filter(${params.subgroup})  # subgroup filter\n` : ""}
dsn <- svydesign(ids = ~SDMVPSU, strata = ~SDMVSTRA, weights = ~wt, nest = TRUE, data = pooled)
options(survey.lonely.psu = "adjust")

fit <- ${fitCall}
print(summary(fit))
${dr ? `# For a dose-response curve, predict over a grid of exposure values:
grid <- data.frame(\`${exposure}\` = seq(min(pooled$\`${exposure}\`, na.rm = TRUE), max(pooled$\`${exposure}\`, na.rm = TRUE), length = 50))
print(predict(fit, newdata = grid, se.fit = TRUE))` : ""}

${R_FOOTER}
`;
}

