import type { VariableEntry } from "../types.js";
import { CYCLE_TO_SERIES } from "../types.js";

/**
 * Generate reproducible R code for survey-weighted mean computation.
 */
export function generateMeanCode(
  variable: VariableEntry,
  params: { subgroup?: string; cycles?: string[] }
): string {
  const series = params.cycles?.map((c) => CYCLE_TO_SERIES[c] ?? c) ?? [];
  const seriesFilter =
    series.length > 0
      ? `series <- c(${series.map((s) => `"${s}"`).join(", ")})`
      : "# All available cycles";

  return `# Survey-weighted mean of ${variable.description} (${variable.variableName})
# Generated by ExposomeQL on ${new Date().toISOString()}

library(survey)
library(nhanespewas)
library(dplyr)

con <- connect_pewas_data("path/to/nhanes_031725.sqlite")
${seriesFilter}

# Get and merge tables
tab_obj <- get_tables("${variable.variableName}", "${variable.variableName}", series, con)
tab_obj <- figure_out_weight(tab_obj)

# Create survey design
dat <- tab_obj$merged_tab |>
  filter(!is.na(wt), wt > 0, !is.na(${variable.variableName}))
${params.subgroup ? `dat <- dat |> filter(${params.subgroup})` : ""}

dsn <- svydesign(
  ids = ~SDMVPSU, strata = ~SDMVSTRA,
  weights = ~wt, nest = TRUE, data = dat
)
options(survey.lonely.psu = "adjust")

# Compute survey-weighted mean
result <- svymean(~${variable.variableName}, design = dsn, na.rm = TRUE)
ci <- confint(result)

cat(sprintf("Mean: %.4f (95%% CI: %.4f - %.4f)\\n", coef(result), ci[1], ci[2]))
cat(sprintf("SE: %.4f\\n", SE(result)))
cat(sprintf("N (unweighted): %d\\n", nrow(dat)))

disconnect_pewas_data(con)
`;
}

/**
 * Generate reproducible R code for prevalence computation.
 */
export function generatePrevalenceCode(
  variable: VariableEntry,
  params: { condition: string; subgroup?: string; cycles?: string[] }
): string {
  return `# Survey-weighted prevalence: ${params.condition}
# Generated by ExposomeQL on ${new Date().toISOString()}

library(survey)
library(nhanespewas)
library(dplyr)

con <- connect_pewas_data("path/to/nhanes_031725.sqlite")

# Get and merge tables, create survey design
tab_obj <- get_tables("${variable.variableName}", "${variable.variableName}", series, con)
tab_obj <- figure_out_weight(tab_obj)
dat <- tab_obj$merged_tab |>
  filter(!is.na(wt), wt > 0, !is.na(${variable.variableName})) |>
  mutate(condition = as.numeric(${params.condition}))
${params.subgroup ? `dat <- dat |> filter(${params.subgroup})` : ""}

dsn <- svydesign(
  ids = ~SDMVPSU, strata = ~SDMVSTRA,
  weights = ~wt, nest = TRUE, data = dat
)
options(survey.lonely.psu = "adjust")

# Compute prevalence
result <- svymean(~condition, design = dsn, na.rm = TRUE)
ci <- confint(result)

cat(sprintf("Prevalence: %.1f%% (95%% CI: %.1f%% - %.1f%%)\\n",
  coef(result) * 100, ci[1] * 100, ci[2] * 100))

disconnect_pewas_data(con)
`;
}

/**
 * Generate reproducible R code for conditional analysis.
 */
export function generateConditionalCode(
  outcome: VariableEntry,
  given: VariableEntry,
  params: { bins?: number; subgroup?: string }
): string {
  const nBins = params.bins ?? 10;
  return `# Survey-weighted conditional mean: ${outcome.variableName} by ${given.variableName}
# Generated by ExposomeQL on ${new Date().toISOString()}

library(survey)
library(nhanespewas)
library(dplyr)

con <- connect_pewas_data("path/to/nhanes_031725.sqlite")

# Get merged data with both variables
# ... (use get_tables for both variables)

dsn <- svydesign(
  ids = ~SDMVPSU, strata = ~SDMVSTRA,
  weights = ~wt, nest = TRUE, data = dat
)
options(survey.lonely.psu = "adjust")

# Create ${nBins} bins of the conditioning variable
breaks <- svyquantile(~${given.variableName}, dsn, quantiles = seq(0, 1, length = ${nBins + 1}), na.rm = TRUE)
dat$bin <- cut(dat$${given.variableName}, breaks = breaks[[1]], include.lowest = TRUE)

# Compute conditional means
result <- svyby(~${outcome.variableName}, ~bin, dsn, svymean, na.rm = TRUE)
print(result)

disconnect_pewas_data(con)
`;
}
